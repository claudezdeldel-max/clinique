import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('finance copiée : dépenses, reliquats, persistance et synchronisation patients', async ({ page, request }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const patientResponse = await request.post('/api/patients', { data: { first_name: 'Finance', last_name: randomUUID().slice(0, 8) } })
  expect(patientResponse.ok()).toBeTruthy()
  const patient = await patientResponse.json()
  const paymentResponse = await request.post('/api/payments', { data: { patient_id: patient.id, total_fee: 3000.2, paid_amount: 500.1, exam_type: 'IRM Cérébrale' } })
  expect(paymentResponse.ok(), await paymentResponse.text()).toBeTruthy()
  const payment = await paymentResponse.json()
  const initial = await (await request.get('/api/finance/dashboard?period=mois')).json()

  const collection = { amount: 500, method: initial.payment_methods[0], request_id: randomUUID() }
  const endpoint = `/api/finance/payments/${payment.id}/collect`
  const repeated = await Promise.all([request.post(endpoint, { data: collection }), request.post(endpoint, { data: collection })])
  for (const result of repeated) { expect(result.ok(), await result.text()).toBeTruthy(); expect((await result.json()).due_balance).toBe(2000.1) }
  expect((await request.post(endpoint, { data: { ...collection, amount: 700 } })).status()).toBe(400)
  expect((await request.post(endpoint, { data: { ...collection, amount: 2001, request_id: randomUUID() } })).status()).toBe(400)
  expect((await request.post(endpoint, { data: { ...collection, amount: 10, method: 'invalid', request_id: randomUUID() } })).status()).toBe(400)
  const after = await (await request.get('/api/finance/dashboard')).json()
  expect(after.summary.revenue - initial.summary.revenue).toBeCloseTo(500, 2)
  expect(after.chart.revenue.reduce((a: number, b: number) => a + b, 0)).toBe(after.summary.revenue)
  expect(after.paiements.filter((p: any) => p.ref === payment.receipt_no)).toHaveLength(2)

  await page.goto('/finance')
  const frame = page.frameLocator('iframe[title="Finance et Comptabilité"]')
  await expect(frame.getByRole('heading', { name: 'Finance & Comptabilité', exact: true })).toBeVisible()
  expect(await frame.locator('.xl\\:grid-cols-4').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(4)
  await expect(frame.getByRole('button', { name: 'Comptabilité', exact: true })).toBeDisabled()
  await expect(frame.getByRole('button', { name: 'Nouvelle écriture', exact: true })).toBeDisabled()
  await expect(frame.getByRole('button', { name: /Exporter/ })).toHaveCount(0)
  await frame.getByRole('button', { name: 'Factures impayées' }).click()
  let row = frame.getByRole('row').filter({ hasText: payment.receipt_no })
  await row.getByRole('button', { name: 'Encaisser', exact: true }).click()
  const dialog = frame.getByRole('dialog', { name: 'Encaisser un règlement' })
  await dialog.getByLabel('Montant encaissé', { exact: true }).fill('1000')
  await dialog.getByRole('button', { name: 'Enregistrer le règlement' }).click()
  await expect(dialog).toBeHidden()
  const balances = await (await request.get('/api/payments/patient-balances')).json()
  expect(balances.find((b: any) => b.patient_id === patient.id).due_balance).toBeCloseTo(1000.1, 2)
  row = frame.getByRole('row').filter({ hasText: payment.receipt_no })
  await row.getByRole('button', { name: 'Encaisser', exact: true }).click()
  await frame.getByRole('dialog', { name: 'Encaisser un règlement' }).getByRole('button', { name: 'Enregistrer le règlement' }).click()
  await expect(frame.getByRole('dialog', { name: 'Encaisser un règlement' })).toBeHidden()
  await expect(row).toHaveCount(0)
  const allPayments = await (await request.get('/api/payments')).json()
  const paid = allPayments.find((p: any) => p.id === payment.id)
  expect(paid.paid_amount).toBe(3000.2); expect(paid.due_balance).toBe(0); expect(paid.payment_status).toBe('Paid')

  await frame.getByRole('button', { name: 'Dépenses', exact: true }).click()
  await frame.getByRole('button', { name: 'Ajouter une dépense', exact: true }).click()
  const expenseDialog = frame.getByRole('dialog', { name: 'Ajouter une dépense' })
  const description = `Consommables QA ${randomUUID().slice(0, 8)}`
  await expenseDialog.getByLabel('Libellé', { exact: true }).fill(description)
  await expenseDialog.getByLabel('Fournisseur', { exact: true }).fill(description)
  await expenseDialog.getByLabel('Montant de la dépense', { exact: true }).fill('1234.56')
  await expenseDialog.getByRole('button', { name: 'Enregistrer la dépense' }).click()
  await expect(expenseDialog).toBeHidden()
  await expect(frame.getByRole('table').filter({ hasText: 'Fournisseur' })).toContainText(description)
  await page.reload()
  await frame.getByRole('button', { name: 'Dépenses', exact: true }).click()
  await expect(frame.getByRole('table').filter({ hasText: 'Fournisseur' })).toContainText(description)
  const final = await (await request.get('/api/finance/dashboard')).json()
  expect(final.summary.expenses - initial.summary.expenses).toBeCloseTo(1234.56, 2)
  expect(final.summary.treasury - initial.summary.treasury).toBeCloseTo(2500.1 - 1234.56, 2)
  expect(final.exams.some((exam: any) => exam.name === 'IRM Cérébrale')).toBeTruthy()
  expect(final.exams.some((exam: any) => exam.name === initial.payment_methods[0])).toBeFalsy()
  expect(final.exams.reduce((total: number, exam: any) => total + exam.amount, 0)).toBeCloseTo(final.summary.revenue, 2)
  await expect(frame.getByRole('heading', { name: 'Répartition par examen', exact: true })).toBeVisible()
  for (const [label, period] of [['Aujourd’hui', 'jour'], ['Cette semaine', 'semaine']]) {
    const changed = page.waitForResponse(response => response.url().includes(`/api/finance/dashboard?period=${period}`) && response.ok())
    await frame.getByRole('button', { name: label, exact: true }).click()
    const selected = await (await changed).json()
    expect(selected.period).toBe(period)
    if (period === 'jour') expect(selected.start).toBe(selected.today)
    else expect(new Date(selected.start).getUTCDay()).toBe(1)
    expect(selected.chart.revenue.reduce((total: number, amount: number) => total + amount, 0)).toBeCloseTo(selected.summary.revenue, 2)
  }
  await frame.getByRole('button', { name: 'Année', exact: true }).click()
  await expect(frame.getByRole('button', { name: 'Année', exact: true })).toHaveClass(/bg-indigo-600/)
  await page.screenshot({ path: 'scratch/finance-connected-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(frame.getByRole('heading', { name: 'Finance & Comptabilité', exact: true })).toBeVisible()
  await page.screenshot({ path: 'scratch/finance-connected-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})

test('les filtres jour et semaine excluent une dépense antérieure à la semaine', async ({ request }) => {
  const before = await (await request.get('/api/finance/dashboard?period=jour')).json()
  const week = await (await request.get('/api/finance/dashboard?period=semaine')).json()
  const sunday = new Date(week.start)
  sunday.setUTCDate(sunday.getUTCDate() - 1)
  const expense = { description: 'Paiement semaine précédente', category: 'Maintenance', amount: 777.11, date: sunday.toISOString().slice(0, 10), method: before.payment_methods[0], request_id: randomUUID() }
  expect((await request.post('/api/finance/expenses', { data: expense })).ok()).toBeTruthy()
  const dayAfter = await (await request.get('/api/finance/dashboard?period=jour')).json()
  const weekAfter = await (await request.get('/api/finance/dashboard?period=semaine')).json()
  expect(dayAfter.summary.expenses).toBe(before.summary.expenses)
  expect(weekAfter.summary.expenses).toBe(week.summary.expenses)
  expect(dayAfter.summary.treasury).toBeCloseTo(before.summary.treasury - expense.amount, 2)
})
