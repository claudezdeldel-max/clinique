import { test, expect } from '@playwright/test'

test('RDV : tableau conservé, vues copiées, dates réelles et actions synchronisées', async ({ page, request }) => {
  test.setTimeout(90000)
  expect((await request.post('/api/test/reset')).ok()).toBeTruthy()
  const accounts = await (await request.get('/api/auth/accounts')).json()
  const admin = accounts.accounts.find((account: any) => account.role === 'admin')
  const session = await (await request.post('/api/auth/select-account', { data: { account_id: admin.id } })).json()
  await page.addInitScript(session => {
    localStorage.setItem('radiomed-account', JSON.stringify({ state: { token: session.token, user: session.user }, version: 0 }))
    localStorage.setItem('clinique-theme-settings', JSON.stringify({ state: { designStyle: 'mediscan' }, version: 0 }))
  }, session)
  await page.route(/https:\/\/(fonts\.(googleapis|gstatic)\.com|cdnjs\.cloudflare\.com)\//, route => route.abort())
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1100 })
  const rooms = await (await request.get('/api/rooms')).json()
  const doctors = await (await request.get('/api/doctors')).json()
  const doctor = doctors[0].name
  const irm = rooms.find((room: any) => room.type.includes('IRM'))
  const scanner = rooms.find((room: any) => room.type.includes('Scanner'))
  async function appointment(name: string, date: string, exam: string, room: string, time = '09:30') {
    const patient = await (await request.post('/api/patients', { data: { first_name: name, last_name: 'Calendrier' } })).json()
    const result = await request.post('/api/appointments', { data: { patient_id: patient.id, patient_name: patient.name, date_time: `${date} ${time}`, time, exam_type: exam, room, radiologist: doctor, duration: '30 min' } })
    expect(result.ok(), await result.text()).toBeTruthy()
    return await result.json()
  }
  const first = await appointment('Patient bissextile', '2028-02-29', 'IRM Cérébrale', irm.name)
  const overlap = await appointment('Patient Scanner', '2028-02-29', 'Scanner Abdomen', scanner.name)
  const nextMonth = await appointment('Patient mars', '2028-03-01', 'IRM Cérébrale', irm.name)
  const earlier = await appointment('Patient semaine précédente', '2028-02-22', 'IRM Cérébrale', irm.name)
  await page.goto('/rendez-vous')
  await expect(page.getByRole('link', { name: 'Consultation', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Secrétariat', exact: true })).toHaveCount(0)
  const calendar = page.getByTestId('rdv-reference')
  await expect(calendar.getByRole('tab', { name: 'Tableau', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByLabel('Date du planning', { exact: true }).fill('2028-02-29')
  await expect(page.getByRole('table')).toContainText(first.patient_name)
  await expect(page.getByRole('table')).toContainText(overlap.patient_name)
  await expect(page.getByRole('table').locator('th')).toHaveText(['Date', 'Heure & Durée', 'Patient', 'Examen / Modalité', "Salle d'Imagerie", 'Radiologue', 'Priorité', 'Statut', 'Actions'])

  await calendar.getByRole('tab', { name: 'Semaine', exact: true }).click()
  await expect(calendar.locator('.week-day-col')).toHaveCount(7)
  await expect(calendar.locator('.week-event')).toHaveCount(3)
  await expect(calendar).toContainText(nextMonth.patient_name)
  await expect(calendar).not.toContainText(earlier.patient_name)
  const firstEvent = calendar.locator(`.week-event[data-id="${first.id}"]`)
  const secondEvent = calendar.locator(`.week-event[data-id="${overlap.id}"]`)
  const firstBox = await firstEvent.boundingBox(), secondBox = await secondEvent.boundingBox()
  expect(firstBox!.x + firstBox!.width).toBeLessThanOrEqual(secondBox!.x + 1)
  await calendar.getByLabel('Examen du calendrier').selectOption('IRM')
  await expect(calendar.locator('.week-event')).toHaveCount(2)
  await calendar.getByLabel('Examen du calendrier').selectOption('all')
  await page.screenshot({ path: 'scratch/rdv-week-connected.png', fullPage: true })

  await firstEvent.click()
  await expect(page.getByRole('dialog')).toContainText('Modification du Rendez-Vous')
  await page.getByLabel('Téléphone', { exact: true }).fill('0555001122')
  await page.getByTestId('appt-submit-btn').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const saved = (await (await request.get('/api/appointments?auto_queue=false')).json()).find((appt: any) => appt.id === first.id)
  expect(saved.patient_phone.replace(/\D/g, '')).toBe('0555001122')

  await calendar.getByRole('button', { name: 'Période précédente', exact: true }).click()
  await expect(calendar).toContainText(earlier.patient_name)
  await expect(calendar).not.toContainText(first.patient_name)
  await calendar.getByRole('button', { name: 'Période suivante', exact: true }).click()
  await calendar.getByRole('tab', { name: 'Mois', exact: true }).click()
  await expect(calendar.locator('.calendar-day:not(.other-month)')).toHaveCount(29)
  await expect(calendar).not.toContainText(nextMonth.patient_name)
  await page.screenshot({ path: 'scratch/rdv-month-connected.png', fullPage: true })
  await calendar.getByRole('button', { name: '29 février 2028', exact: true }).locator('.day-number').click()
  await expect(calendar.getByRole('tab', { name: 'Jour', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(calendar.locator('.day-event')).toHaveCount(2)
  await page.screenshot({ path: 'scratch/rdv-day-connected.png', fullPage: true })

  await calendar.locator('.day-slot[data-time="15:00"]').click({ position: { x: 15, y: 15 } })
  await expect(page.getByRole('dialog')).toContainText('Prise de Rendez-Vous Examen')
  await expect(page.getByTestId('appt-date-input')).toHaveValue('2028-02-29')
  await page.getByRole('button', { name: /Nouveau Patient/ }).click()
  await page.getByTestId('appt-patient-name').fill('Patient créé depuis le calendrier')
  await page.getByTestId('appt-submit-btn').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(calendar).toContainText('Patient créé depuis le calendrier')

  await calendar.getByRole('tab', { name: 'Liste', exact: true }).click()
  const card = calendar.locator(`.rdv-card[data-id="${first.id}"]`)
  await card.getByRole('button', { name: `Confirmer ${first.patient_name}`, exact: true }).click()
  await expect(card.locator('.rdv-status')).toHaveText('Confirmé')
  await card.getByRole('button', { name: `Annuler ${first.patient_name}`, exact: true }).click()
  await page.getByRole('button', { name: 'Confirmer l’annulation', exact: true }).click()
  await expect(card.locator('.rdv-status')).toHaveText('Annulé')
  await calendar.getByLabel('Statut du calendrier').selectOption('cancelled')
  await expect(calendar.locator('.rdv-card')).toHaveCount(1)
  await calendar.getByLabel('Statut du calendrier').selectOption('all')
  await page.screenshot({ path: 'scratch/rdv-list-connected.png', fullPage: true })
  await calendar.getByRole('tab', { name: 'Tableau', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: first.patient_name })).toContainText('Annulé')
  await page.getByTestId(`mark-arrived-${overlap.id}`).click()
  await expect(page.getByRole('row').filter({ hasText: overlap.patient_name })).toContainText('En file')
  const queue = await (await request.get('/api/queue')).json()
  expect(queue.some((ticket: any) => ticket.appointment_id === overlap.id)).toBeTruthy()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Consultation', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Secrétariat', exact: true })).toHaveCount(0)
  await calendar.getByRole('tab', { name: 'Semaine', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(calendar.getByRole('tab', { name: 'Jour', exact: true })).toBeVisible()
  await expect(calendar.getByRole('tab', { name: 'Liste', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
  await page.screenshot({ path: 'scratch/rdv-calendar-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
