import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('recherche et sélection des patients dans RDV et file, création avec +', async ({ page, request }) => {
  test.setTimeout(60000)
  const tag = randomUUID().slice(0, 8)
  const patient = await (await request.post('/api/patients', { data: { first_name: 'Recherche', last_name: tag } })).json()
  await page.goto('/rendez-vous')
  await page.getByTestId('new-appointment-btn').click()
  let dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Nouveau rendez-vous')
  await expect(dialog.getByRole('button', { name: 'Nouveau patient', exact: true })).toBeVisible()
  await dialog.getByRole('combobox', { name: 'Rechercher un patient' }).fill(tag)
  await dialog.getByRole('option', { name: patient.name, exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'Rechercher un patient' })).toHaveValue(patient.name)
  await page.getByTestId('appt-date-input').fill('2034-07-12')
  await dialog.getByRole('button', { name: '16:30', exact: true }).click()
  await page.getByTestId('appt-submit-btn').click()
  await expect(dialog).toHaveCount(0)
  const appointments = await (await request.get('/api/appointments?auto_queue=false')).json()
  expect(appointments.some((appt: any) => appt.patient_id === patient.id && appt.date_time.startsWith('2034-07-12'))).toBeTruthy()
  await page.getByTestId('new-appointment-btn').click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Nouveau patient', exact: true }).click()
  await expect(dialog.getByLabel('Nom et prénom *', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Rechercher un patient', exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'Rechercher un patient' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()

  await page.goto('/queue-management')
  await page.getByRole('button', { name: 'Nouveau Ticket Patient', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Nouveau ticket')
  await dialog.getByRole('combobox', { name: 'Rechercher un patient' }).fill(tag)
  await dialog.getByRole('option', { name: patient.name, exact: true }).click()
  await dialog.getByRole('button', { name: 'Ajouter', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const tickets = await (await request.get('/api/queue')).json()
  expect(tickets.some((ticket: any) => ticket.patient_id === patient.id)).toBeTruthy()
  await page.getByRole('button', { name: 'Nouveau Ticket Patient', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Nouveau patient', exact: true }).click()
  await dialog.getByLabel('Nom et prénom *', { exact: true }).fill(`Nouveau Picker ${tag}`)
  await dialog.getByRole('button', { name: 'Ajouter', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const patients = await (await request.get(`/api/patients?search=${tag}`)).json()
  expect(patients.items.some((p: any) => p.name.toLowerCase().includes('nouveau picker'))).toBeTruthy()
  await page.goto('/patients')
  await expect(page.getByRole('heading', { name: 'Gestion des patients', exact: true })).toBeVisible()
})
